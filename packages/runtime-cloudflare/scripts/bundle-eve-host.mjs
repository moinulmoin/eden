import { build } from "esbuild";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const outfile = join(packageRoot, "dist", "eden-eve-host-worker.mjs");

await rm(outfile, { force: true });
await mkdir(dirname(outfile), { recursive: true });

const result = await build({
  entryPoints: [join(packageRoot, "src", "eve-host-runtime.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  external: ["cloudflare:workers"],
  outfile,
  metafile: true,
  logLevel: "silent",
  legalComments: "inline",
});

const outputs = Object.entries(result.metafile.outputs);
const bundleOutput = outputs.find(([path]) => path.endsWith("eden-eve-host-worker.mjs"));
if (bundleOutput === undefined) {
  throw new Error("The Eve host worker bundle was not produced.");
}
const externalImports = bundleOutput[1].imports
  .filter((entry) => entry.external)
  .map((entry) => entry.path);
if (
  externalImports.length !== 1 ||
  externalImports[0] !== "cloudflare:workers"
) {
  throw new Error(
    `The Eve host worker bundle must externalize only cloudflare:workers; observed ${JSON.stringify(externalImports)}.`,
  );
}

const banner = `// @moinulmoin/eden-runtime-cloudflare Eve host worker runtime bundle.
// Generated by scripts/bundle-eve-host.mjs; do not edit.
// Bundles @cloudflare/containers (Apache-2.0) with cloudflare:workers external.
`;
const body = await readFile(outfile, "utf8");
await writeFile(outfile, `${banner}\n${body}`);
process.stdout.write(`bundled ${outfile} (${bundleOutput[1].bytes} bytes)\n`);
